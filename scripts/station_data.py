def fetch_raw():
    """获取 12306 官方全部车站原始数据"""
    url = "https://kyfw.12306.cn/otn/resources/js/framework/station_name.js"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    data = urllib.request.urlopen(req, timeout=30).read().decode("utf-8")
    m = re.search(r"station_names\s*=\s*'([^']+)'", data)
    if not m:
        return []
    raw = m.group(1)
    stations = []
    for part in raw.split("@"):
        if not part.strip():
            continue
        fields = part.split("|")
        if len(fields) >= 8:
            name, code, city = fields[1], fields[2], fields[7]
            if not city or city in SKIP_CITIES:
                continue
            bureau = fields[6] if len(fields) > 6 else ""
            stations.append({"name": name, "code": code, "city": city, "bureau": bureau})
    return stations


def classify_station(name, city):
    """统一的车站类型判定"""
    HUBS = {"北京","上海","广州","深圳","武汉","郑州","西安","成都","沈阳","南京","杭州","重庆","天津","长沙","昆明","南宁","贵阳","兰州","哈尔滨","长春","济南","石家庄","太原","合肥","南昌","福州","乌鲁木齐","呼和浩特","拉萨","海口"}
    is_hub = city in HUBS and (name == city or name == city + "站")
    is_dir = name[-1] in "东南西北"
    if is_hub:
        return "HUB"
    elif is_dir:
        return "HIGH_SPEED"
    return "NORMAL"


NON_PASSENGER_KW = ["乘降所","线路所","货场","编组","运转","机务","车辆","动车所"]

DIRECTIONS = [("北",0.02,0),("南",-0.02,0),("东",0,0.02),("西",0,-0.02)]


def gen_coords(stations):
    """为车站列表生成坐标（基于城市+铁路局+站名微调）"""
    import hashlib
    result = []
    for sid, s in enumerate(stations, 1):
        name, city, bureau = s["name"], s["city"], s["bureau"]
        if city in CITY_COORDS:
            lat, lng = CITY_COORDS[city]
        elif name in CITY_COORDS:
            lat, lng = CITY_COORDS[name]
        else:
            bp = bureau[:2] if len(bureau) >= 2 else "00"
            lat, lng = BUREAU_COORDS.get(bp, (35.0, 110.0))
        h = int(hashlib.md5(name.encode()).hexdigest()[:4], 16) % 100
        if name == city or name == city + "站":
            lat += 0.001 * (h % 3 - 1)
            lng += 0.001 * ((h // 3) % 3 - 1)
        else:
            lat += 0.003 * (h % 7 - 3)
            lng += 0.003 * ((h // 7) % 7 - 3)
            for d, dl, dg in DIRECTIONS:
                if name.endswith(d):
                    lat += dl; lng += dg
        stype = classify_station(name, city)
        result.append({"id": sid, "name": name, "city": city, "type": stype,
                       "latitude": round(lat, 4), "longitude": round(lng, 4)})
    return result
