def fetch_stations():
    """获取 12306 官方车站列表"""
    url = "https://kyfw.12306.cn/otn/resources/js/framework/station_name.js"
    print(f"获取 {url} ...")
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    data = urllib.request.urlopen(req, timeout=30).read().decode("utf-8")
    # 提取 var station_names ='...';
    m = re.search(r"station_names\s*=\s*'([^']+)'", data)
    if not m:
        print("解析失败")
        return []
    raw = m.group(1)
    stations = []
    for part in raw.split("@"):
        if not part.strip():
            continue
        fields = part.split("|")
        if len(fields) >= 6:
            stations.append({
                "name": fields[1],
                "code": fields[2],
                "city": fields[7] if len(fields) > 7 else "",
                "pinyin": fields[3],
                "id": fields[5],
            })
    print(f"共解析 {len(stations)} 个车站")
    return stations


def select_major(all_stations):
    """筛选主要车站（客运站，排除乘降所和纯货运站）"""
    selected = []
    seen_cities = set()
    for s in all_stations:
        name = s["name"]
        city = s["city"]
        if not city:
            continue
        # 跳过境外/无效城市
        if city in SKIP_CITIES:
            continue
        # 跳过纯货运/乘降所类小站
        if any(kw in name for kw in ["乘降所", "线路所", "货场", "编组", "运转"]):
            continue
        # 按城市去重：每个城市保留主要车站（优先保留带"北/南/东/西"或直接是城市名的）
        city_key = city
        if city_key in seen_cities:
            continue
        # 只保留重要车站：站名 ≤ 5 字，包含常见关键字
        if len(name) <= 5 and (
            name == city or
            name.startswith(city) or
            any(suffix in name for suffix in ["北", "南", "东", "西", "站"])
        ):
            seen_cities.add(city_key)
            selected.append(s)

    print(f"筛选后保留 {len(selected)} 个主要车站")
    return selected


def gen_stations_json(selected):
    """生成 stations.json"""
    result = []
    station_id = 1
    for s in selected:
        city = s["city"]
        coord = CITY_COORDS.get(city, (36.0, 110.0))
        # 确定车站类型
        name = s["name"]
        if "北" not in name and "南" not in name and "东" not in name and "西" not in name:
            stype = "HUB"  # 主站是枢纽站
        elif any(kw in name for kw in ["高铁", "城际"]):
            stype = "HIGH_SPEED"
        elif "东" in name or "西" in name:
            stype = "HIGH_SPEED"
        else:
            stype = "NORMAL"

        # 微调坐标：同一城市的车站略偏移
        lat, lng = coord
        if "北" in name:
            lat += 0.03
        elif "南" in name:
            lat -= 0.03
        if "东" in name:
            lng += 0.03
        elif "西" in name:
            lng -= 0.03

        result.append({
            "id": station_id,
            "name": name,
            "city": city,
            "type": stype,
            "latitude": round(lat, 2),
            "longitude": round(lng, 2),
        })
        station_id += 1

    path = os.path.join(CONFIG_DIR, "stations.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print(f"已写入 {path} ({len(result)} 个站点)")


